import Foundation
import Testing
@testable import RescueCore

@Suite struct FlowCardTests {
    private func coreEngine() throws -> ProtocolEngine { ProtocolEngine(bundle: try loadBundle()) }
    private func engine() throws -> ProtocolEngine { ProtocolEngine(bundle: try loadMergedBundle()) }

    private func labels(_ card: HandoffCard) -> [String] { card.items.map(\.label) }

    private func value(_ label: String, _ card: HandoffCard) -> HandoffCard.Item? {
        card.items.first { $0.label == label }
    }

    private func card(_ session: Session) -> HandoffCard { HandoffBuilder.build(from: session.log.entries) }

    private let arrestRows: Set = ["Coaching started", "AED arrived", "Pads on", "Shocks marked", "Patient moved"]
    private let todaysRows = ["Responding", "Breathing normally", "Coaching started", "911 prompted", "AED arrived", "Pads on", "Shocks marked", "Patient moved"]

    private func inFlow(by finding: Finding? = nil) throws -> Session {
        var session = Session(engine: try engine())
        session.now += 6
        session.human(.yes)
        session.now += 3
        if let finding {
            session.modelFinding(finding)
        } else {
            session.human(.triageChest)
        }
        return session
    }

    private func script(_ session: Session) -> CallerScript {
        CallerScriptBuilder.build(from: session.log.entries, location: nil, resources: session.state.resources)
    }

    // MARK: - With no flow, exactly today's card

    /// Written out by hand from the card as it stood before flows existed.
    @Test func aLogWithNoFlowGivesTodaysCard() throws {
        var session = Session(engine: try coreEngine())
        session.human(.no)
        session.now += 4
        session.modelFinding(.abnormalBreathing)
        session.now += 3
        session.human(.called)
        session.human(.done)
        session.human(.done)
        session.now += 20
        session.human(.aedHere)
        session.human(.padsOn)
        session.human(.shockDelivered)
        session.human(.shockDelivered)

        let built = card(session)
        #expect(built.items == [
            .init(label: "Responding", value: "no", source: .bystander, time: "T+0:00"),
            .init(label: "Breathing normally", value: "no, abnormal", source: .aiInferred, time: "T+0:04"),
            .init(label: "Coaching started", value: "T+0:07", source: .timer),
            .init(label: "911 prompted", value: "T+0:04", source: .timer),
            .init(label: "AED arrived", value: "T+0:27", source: .bystander),
            .init(label: "Pads on", value: "T+0:27", source: .bystander),
            .init(label: "Shocks marked", value: "2", source: .bystander),
            .init(label: "Patient moved", value: "not recorded", source: nil),
        ])
        #expect(built.timeline == [
            .init(label: "App opened", value: "T+0:00", source: .timer),
            .init(label: "911 prompted", value: "T+0:04", source: .timer),
            .init(label: "Coaching started", value: "T+0:07", source: .timer),
            .init(label: "AED arrived", value: "T+0:27", source: .bystander),
            .init(label: "Pads on", value: "T+0:27", source: .bystander),
            .init(label: "Shock marked", value: "T+0:27", source: .bystander),
            .init(label: "Shock marked", value: "T+0:27", source: .bystander),
        ])
        #expect(built.readout == "Simulation handoff, generated by an app and not verified. Responding: no at T+0:00. Breathing normally: no, abnormal at T+0:04. Coaching started: T+0:07. Pads on: T+0:27. Shocks marked: 2.")
    }

    @Test func nothingYetSaysNotRecorded() throws {
        let built = card(Session(engine: try coreEngine()))
        #expect(labels(built) == todaysRows)
        #expect(built.readout == "Simulation handoff, generated by an app and not verified. Responding: not recorded. Breathing normally: not recorded. Coaching started: not recorded. Pads on: not recorded. Shocks marked: not recorded.")
    }

    /// The merged bundle reaches triage, but until a flow starts the card has nothing new to say.
    @Test func triageAloneChangesNothingOnTheCard() throws {
        var merged = Session(engine: try engine())
        merged.human(.yes)
        var core = Session(engine: try coreEngine())
        core.human(.yes)
        #expect(merged.entries(.flowEntered).isEmpty)
        #expect(card(merged) == card(core))
        #expect(script(merged) == script(core))
    }

    @Test func theCallerScriptIsTodaysWithNoFlow() throws {
        var session = Session(engine: try coreEngine())
        session.human(.yes)
        #expect(script(session).situation == "Adult unwell, responding.")
        #expect(script(session).readAloud == "I am an AI assistant speaking for the caller. This is a simulation. Adult unwell, responding. The caller will confirm the location.")
    }

    // MARK: - With a flow

    @Test func theConcernLeadsTheCard() throws {
        let built = card(try inFlow())
        #expect(built.items.first == .init(label: "Concern", value: "Possible heart attack. Not a diagnosis.", source: .bystander, time: "T+0:09"))
        #expect(built.timeline.contains(.init(label: "Concern: possible heart attack", value: "T+0:09", source: .bystander)))
        #expect(built.readout.contains("Concern: possible heart attack, not a diagnosis."))
    }

    @Test func aConcernTheAIChoseIsTaggedAsTheAIs() throws {
        let built = card(try inFlow(by: .chestPain))
        #expect(value("Concern", built)?.source == .aiInferred)
    }

    @Test func arrestRowsHideWhileCoachingNeverStarted() throws {
        var session = try inFlow()
        session.human(.done)
        session.human(.yes)
        let built = card(session)
        let shown = Set(labels(built))
        #expect(shown.isDisjoint(with: arrestRows), "\(shown)")
        #expect(shown.isSuperset(of: ["Concern", "Responding", "Breathing normally", "911 prompted"]))
        for row in ["Coaching started", "Pads on", "Shocks marked"] {
            #expect(!built.readout.contains(row), "\(row)")
        }
        #expect(value("Responding", built)?.value == "yes")
        #expect(value("911 prompted", built)?.value == "T+0:09")
    }

    /// Only what never happened hides, and this happened with no CPR in between.
    @Test func aPatientWhoMovedIsOnTheCardWithNoCPR() throws {
        var session = try inFlow()
        session.human(.patientUnresponsive)
        session.human(.yes)
        session.now += 5
        session.human(.patientAwake)
        #expect(session.state.stateID == "responsive_patient")
        let built = card(session)
        #expect(value("Patient moved", built)?.value == "T+0:14")
        #expect(value("Coaching started", built) == nil)
    }

    @Test func arrestRowsAllComeBackOnceCoachingStarts() throws {
        var session = try inFlow()
        session.human(.done)
        session.human(.yes)
        session.human(.startCpr)
        let built = card(session)
        #expect(Set(labels(built)).isSuperset(of: todaysRows))
        #expect(value("Pads on", built)?.value == "not recorded")
        #expect(value("Concern", built)?.value == "Possible heart attack. Not a diagnosis.")
        #expect(value("Coaching started", built)?.source == .timer)
        #expect(built.readout.contains("Coaching started: T+0:09."))
        #expect(built.readout.contains("Pads on: not recorded."))
    }

    @Test func aspirinIsAdviceAndNotAFact() throws {
        var session = try inFlow()
        session.human(.done)
        session.now += 4
        session.human(.no)
        let built = card(session)
        let row = try #require(value("Aspirin advised, not confirmed taken", built))
        #expect(row.value == "T+0:13")
        #expect(row.source == .bystander)
        #expect(built.timeline.contains { $0.label == "Aspirin advised, not confirmed taken" && $0.value == "T+0:13" })
        #expect(built.readout.contains("Aspirin advised, not confirmed taken, at T+0:13."))

        let text = (built.items + built.timeline).map(\.label).joined(separator: " ").lowercased() + built.readout.lowercased()
        #expect(!text.contains("aspirin given"))
        #expect(!text.contains("aspirin taken"))
    }

    @Test func noAspirinRowWithoutTheTapThatGivesIt() throws {
        var session = try inFlow()
        session.human(.done)
        session.human(.yes)
        #expect(value("Aspirin advised, not confirmed taken", card(session)) == nil)
    }

    /// A second one can only come from stage control, and a card still can't hide it.
    @Test func everyAdviceIsOnTheCard() throws {
        var log = EventLog()
        log.append([.init(kind: .sessionStarted, source: .timer), .init(kind: .flowEntered, source: .bystander, detail: "possible_heart_attack")], at: 100)
        log.append([.init(kind: .aspirinAdvised, source: .bystander)], at: 110)
        log.append([.init(kind: .aspirinAdvised, source: .system)], at: 130)
        let built = HandoffBuilder.build(from: log.entries)
        let label = "Aspirin advised, not confirmed taken"
        #expect(built.items.filter { $0.label == label }.map(\.value) == ["T+0:10", "T+0:30"])
        #expect(built.timeline.filter { $0.label == label }.map(\.value) == ["T+0:10", "T+0:30"])
        #expect(built.readout.contains("\(label), at T+0:10 and T+0:30."))
    }

    @Test(arguments: [
        (HumanAction.yes, "yes", EvidenceSource.bystander),
        (.no, "no", .bystander),
        (.unsure, "unsure", .bystander),
    ])
    func anAnswerGetsAGenericRow(action: HumanAction, expected: String, source: EvidenceSource) throws {
        var session = try inFlow()
        session.human(.done)
        session.now += 2
        session.human(action)
        let row = try #require(value("Aspirin risk reported", card(session)))
        #expect(row.value == expected)
        #expect(row.source == source)
        #expect(row.time == "T+0:11")
    }

    /// The check repeats rather than timing out, so silence gives no row to read as an answer.
    @Test func silenceLeavesNoAnswerRow() throws {
        var session = try inFlow()
        session.human(.done)
        session.advance(10)
        session.advance(10)
        #expect(session.state.stateID == "chest_aspirin_check")
        #expect(value("Aspirin risk reported", card(session)) == nil)
    }

    /// Its own question rows already cover these.
    @Test func theArrestQuestionsGetNoSecondRow() throws {
        var session = try inFlow()
        session.human(.patientUnresponsive)
        session.human(.no)
        let built = card(session)
        #expect(built.items.filter { $0.label == "Responsive" || $0.label == "Breathing" || $0.label == "Adult" }.isEmpty)
        #expect(value("Responding", built)?.value == "no")
        #expect(value("Breathing normally", built)?.value == "no")
    }

    @Test func aiObservationsAreTaggedAndNotRepeated() throws {
        var session = try inFlow(by: .chestPain)
        session.human(.done)
        session.human(.yes)
        session.now += 1
        session.model(.reportFinding(.limbInjury, source: .seen, confidence: .low))
        session.now += 1
        session.model(.reportFinding(.limbInjury, source: .seen, confidence: .low))
        session.model(.reportFinding(.choking, source: .heard, confidence: .high))

        let rows = card(session).items.filter { $0.label.hasPrefix("AI ") }
        #expect(rows == [
            .init(label: "AI heard", value: "chest pain (high)", source: .aiInferred, time: "T+0:09"),
            .init(label: "AI saw", value: "limb injury (low)", source: .aiInferred, time: "T+0:10"),
            .init(label: "AI heard", value: "choking (high)", source: .aiInferred, time: "T+0:11"),
        ])
    }

    @Test func aCardBuiltFromAForcedWalkSaysSo() throws {
        var session = Session(engine: try engine())
        session.log.append([
            LogEntry.Draft(kind: .stateEntered, source: .system, detail: "operator_forced:chest_wait"),
            LogEntry.Draft(kind: .stateEntered, source: .system, detail: "chest_wait"),
            LogEntry.Draft(kind: .flowEntered, source: .system, detail: "possible_heart_attack"),
        ], at: session.now)
        let built = card(session)
        #expect(value("Concern", built)?.source == .system)
        #expect(value("Responding", built)?.value == "not recorded")
    }

    // MARK: - A concern taken back

    @Test func goingBackLeavesItOnTheRecordButNotAsCurrent() throws {
        var session = try inFlow()
        session.now += 5
        session.human(.notThis)
        let built = card(session)
        #expect(value("Concern", built)?.value == "Possible heart attack earlier, not confirmed since. Not a diagnosis.")
        #expect(built.readout.contains("Concern: possible heart attack earlier, not a diagnosis."))
        #expect(!script(session).situation.contains("heart attack"))
    }

    @Test func aCollapseDoesNotTakeItBack() throws {
        var session = try inFlow()
        session.human(.patientUnresponsive)
        #expect(value("Concern", card(session))?.value == "Possible heart attack. Not a diagnosis.")
        #expect(script(session).situation.contains("possible heart attack"))
    }

    @Test func comingBackToItCountsAgain() throws {
        var session = try inFlow()
        session.human(.notThis)
        session.human(.triageChest)
        #expect(value("Concern", card(session))?.value == "Possible heart attack. Not a diagnosis.")
        #expect(card(session).timeline.filter { $0.label == "Concern: possible heart attack" }.count == 2)
    }

    // MARK: - Caller script

    @Test func theCallerScriptSaysPossible() throws {
        var session = try inFlow()
        #expect(script(session).situation == "Adult unwell, responding, possible heart attack.")
        #expect(script(session).readAloud.contains("Adult unwell, responding, possible heart attack."))

        session.human(.patientUnresponsive)
        session.human(.no)
        #expect(script(session).situation == "Adult collapsed, not responding, not breathing normally, possible heart attack.")
    }

    @Test func theCallerScriptSaysWhatTheAIHeard() throws {
        var session = try inFlow(by: .chestPain)
        #expect(script(session).situation == "Adult unwell, responding, possible heart attack, AI reported chest pain.")
        session.modelFinding(.unresponsive)
        session.human(.no)
        #expect(script(session).situation == "Adult collapsed, not responding, not breathing normally, possible heart attack, AI reported chest pain.")
    }

    // MARK: - Wording

    @Test func nothingStatesItAsFact() throws {
        var session = try inFlow(by: .chestPain)
        session.human(.done)
        session.human(.no)
        session.human(.done)
        session.human(.startCpr)
        let built = card(session)
        let text = (built.items + built.timeline).flatMap { [$0.label, $0.value] } + [built.readout, script(session).readAloud]
        for line in text where line.lowercased().contains("heart attack") {
            #expect(line.lowercased().contains("possible heart attack"), "\(line)")
        }
    }

    /// The card builds the name from the id, and the why panel shows the title, so they have to agree.
    @Test func theNameFromTheIdIsTheFlowsTitle() throws {
        for flow in try loadMergedBundle().flows {
            #expect(LogFacts.words(flow.id) == flow.title.lowercased(), "\(flow.id)")
        }
    }

    @Test func theReadoutStillFitsThirtySeconds() throws {
        var session = try inFlow(by: .chestPain)
        session.human(.done)
        session.human(.no)
        session.human(.done)
        session.human(.startCpr)
        session.human(.aedHere)
        session.human(.padsOn)
        session.human(.shockDelivered)
        let readout = card(session).readout
        #expect(readout.split(separator: " ").count <= 75, "\(readout)")
    }
}
